import express from 'express';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import { fileURLToPath } from 'node:url';
import { prisma } from './config/database.js';
import { RESPONSES, sendResponse } from './common/responses.js';
import { errorHandler } from './middleware/errors.js';
import { authRouter } from './auth/auth.routes.js';
import { jobRouter, companyRouter } from './jobs/job.routes.js';
import { applicationRouter } from './applications/application.routes.js';
export const app = express();
app.disable('x-powered-by');
app.use(helmet({ contentSecurityPolicy: { directives: { upgradeInsecureRequests: process.env.NODE_ENV === 'production' ? [] : null } }, strictTransportSecurity: process.env.NODE_ENV === 'production' ? undefined : false }));
app.use(express.json({ limit: '64kb' }));
app.get('/health', async (req, res) => { await prisma.$queryRaw`SELECT 1`; sendResponse(res, RESPONSES.HEALTHY, { data: { database: 'connected' } }); });
app.use('/api', rateLimit({ windowMs: 60000, limit: 180, standardHeaders: 'draft-8', legacyHeaders: false, skip: () => process.env.NODE_ENV === 'test', handler: (req, res) => sendResponse(res, RESPONSES.RATE) }), (req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
app.use('/api/auth', authRouter);
app.use('/api/jobs', jobRouter);
app.use('/api/company', companyRouter);
app.use('/api/applications', applicationRouter);
app.use(express.static(fileURLToPath(new URL('../../frontend/dist', import.meta.url))));
app.use((req, res) => sendResponse(res, RESPONSES.ROUTE));
app.use(errorHandler);
